@contextmanager
def float_model(name: str):
    with ExitStack() as stack:
        if name.endswith("_sum"):
            impl = naive_sum if name == "naive_sum" else neumaier_sum
            for mod in (engine_mod, scoring_mod, secrets_mod, complexity_mod, deps_mod):
                stack.enter_context(mock.patch.object(mod, "sum", impl, create=True))
        elif name.startswith("libm"):
            nudged = _NudgedMath(3 if name == "libm_up" else -3)
            for mod in (scoring_mod, secrets_mod):
                stack.enter_context(mock.patch.object(mod, "math", nudged))
        yield

