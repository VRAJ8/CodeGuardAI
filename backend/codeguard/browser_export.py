# ---------------------------------------------------------------------------------------- Python semantics


def naive_sum(items, start=0):
    """builtin sum() of CPython <= 3.11: plain left-to-right addition."""
    total = start
    for x in items:
        total = total + x
    return total


def neumaier_sum(items, start=0):
    """builtin sum() of CPython >= 3.12: Neumaier-compensated over floats, exact over an all-int prefix."""
    it = iter(items)
    total = start
    for x in it:
        if type(total) is int and type(x) in (int, bool):
            total += x
            continue
        total = total + x
        break
    else:
        return total
    c = 0.0
    for x in it:
        if type(total) is not float or type(x) not in (float, int, bool):
            total = total + x
        elif type(x) is float:
            t = total + x
            c += (total - t) + x if abs(total) >= abs(x) else (x - t) + total
            total = t
        else:
            total += float(x)
    return total + c if type(total) is float and c and math.isfinite(c) else total


class _NudgedMath:
    """`math` with exp/log2 off by a few ulps, standing in for another libm (V8 differs from glibc by <= 2)."""

    def __init__(self, ulps: int):
        self.ulps = ulps

    def __getattr__(self, name):
        return getattr(math, name)

    def _nudge(self, x: float) -> float:
        for _ in range(abs(self.ulps)):
            x = math.nextafter(x, math.inf if self.ulps > 0 else -math.inf)
        return x

    def exp(self, x):
        return math.exp(x) if x == 0 else self._nudge(math.exp(x))

    def log2(self, x):
        exact = math.log2(x)
        return exact if exact.is_integer() else self._nudge(exact)  # powers of two are exact in every libm


