def secret_hits(texts: Dict[str, str]) -> List[str]:
    """Places where a provider signature matches: none may exist in anything committed."""
    hits = []
    for name, text in texts.items():
        for rid, _, rx, _ in secrets_mod.SIGNATURES:
            if re.search(rx, text):
                hits.append(f"{name}: {rid}")
    return hits


def _strings(node: Any) -> Iterator[str]:
    if isinstance(node, str):
        yield node
    elif isinstance(node, dict):
        for k, v in node.items():
            yield k
            yield from _strings(v)
    elif isinstance(node, list):
        for v in node:
            yield from _strings(v)


def check_no_secrets(outputs: Dict[Path, str], golden: dict) -> None:
    texts = {str(p): text for p, text in outputs.items()}
    texts.update({f"golden string #{i}": s for i, s in enumerate(_strings(golden))})
    own = [Path(__file__), BACKEND / "tests" / "test_browser_parity.py"]
    for p in list(CORPUS_DIR.rglob("*")) + list((FIXTURES / "vulnerable_app").rglob("*")) + own:
        if p.is_file():
            texts[str(p)] = p.read_text(encoding="utf-8")
    hits = secret_hits(texts)
    if hits:
        raise SystemExit("provider-format secret literal(s) would be committed; build them from PLACEHOLDERS:\n  "
                         + "\n  ".join(hits[:20]))


def render(obj: dict) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=True) + "\n"


def build() -> Dict[Path, str]:
    golden = build_golden()
    outputs = {RULES_PATH: render(build_rules()), GOLDEN_PATH: render(golden)}
    check_no_secrets(outputs, golden)
    return outputs


def stale(outputs: Dict[Path, str]) -> List[Path]:
    return [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m codeguard.browser_export", description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is out of date")
    args = parser.parse_args(argv)
    outputs = build()
    if args.check:
        out_of_date = stale(outputs)
        for p in out_of_date:
            print(f"{p.relative_to(BACKEND.parent)} is stale: run `{REGEN}`", file=sys.stderr)
        return 1 if out_of_date else 0
    ENGINE_DIR.mkdir(parents=True, exist_ok=True)
    for p, text in outputs.items():
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p.relative_to(BACKEND.parent)} ({len(text) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
