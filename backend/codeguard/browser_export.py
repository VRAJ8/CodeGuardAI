def _first_difference(a: Any, b: Any, path: str = "golden") -> str:
    if isinstance(a, dict) and isinstance(b, dict) and a.keys() == b.keys():
        return next((_first_difference(a[k], b[k], f"{path}.{k}") for k in a if a[k] != b[k]), path)
    if isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
        return next((_first_difference(x, y, f"{path}[{i}]") for i, (x, y) in enumerate(zip(a, b, strict=True)) if x != y), path)
    return f"{path} ({a!r} vs {b!r})"


