def iter_regexes(node: Any, path: str = "") -> Iterator[Tuple[str, dict]]:
    """Every regex spec in the rules, keyed by dotted path (list items by their id). lang.js mirrors this."""
    if isinstance(node, dict):
        if "pattern" in node and "flags" in node:
            yield path, node
        for k, v in node.items():
            if k != "python":
                yield from iter_regexes(v, f"{path}.{k}" if path else k)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            yield from iter_regexes(v, f"{path}.{v['id'] if isinstance(v, dict) and 'id' in v else i}")

