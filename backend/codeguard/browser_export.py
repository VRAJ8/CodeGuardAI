class Untranslatable(ValueError):
    """A Python regex construct with no faithful JavaScript translation."""


WORD = r"\p{L}\p{N}_"
WORD_BOUNDARY = f"(?:(?<=[{WORD}])(?![{WORD}])|(?<![{WORD}])(?=[{WORD}]))"
SYNTAX = set("^$\\.*+?()[]{}|/")
CLASS_SPECIAL = set("\\]-[^")
SIMPLE_ESCAPES = {"n": 0x0A, "t": 0x09, "r": 0x0D, "f": 0x0C, "v": 0x0B, "a": 0x07}
INLINE_FLAGS = {"i": re.IGNORECASE, "m": re.MULTILINE, "s": re.DOTALL, "u": re.UNICODE}
SUPPORTED_FLAGS = int(re.IGNORECASE | re.MULTILINE | re.DOTALL | re.UNICODE)  # int: ~RegexFlag only spans defined flags
REPEAT = re.compile(r"\{([0-9]*)(,?)([0-9]*)\}")  # sre_parse: "{}" and "{x" are literals, "{,n}" is 0..n


@lru_cache(maxsize=1)
def _every_char() -> str:
    return "".join(chr(cp) for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF)


@lru_cache(maxsize=1)
def python_whitespace() -> Tuple[int, ...]:
    """Code points Python's \\s, str.split() and str.strip() treat as whitespace."""
    cps = tuple(ord(c) for c in re.findall(r"\s", _every_char()))
    assert cps == tuple(ord(c) for c in _every_char() if c.isspace()), "re's \\s and str.isspace() disagree"
    return cps


@lru_cache(maxsize=1)
def python_line_breaks() -> Tuple[int, ...]:
    """Code points str.splitlines() breaks on (it also treats CR LF as one break)."""
    return tuple(cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF and len(f"a{chr(cp)}b".splitlines()) == 2)


@lru_cache(maxsize=None)
def _case_delta(atom: str) -> Tuple[Tuple[int, ...], Tuple[int, ...]]:
    """Characters Python's IGNORECASE adds to and removes from a one-character atom."""
    every = _every_char()
    added = re.findall(f"(?i)(?!(?-i:{atom})){atom}", every)
    removed = re.findall(f"(?i)(?!{atom})(?-i:{atom})", every)
    return tuple(map(ord, added)), tuple(map(ord, removed))


def _char(cp: int, in_class: bool) -> str:
    ch = chr(cp)
    if ch in "\n\t\r":
        return {"\n": r"\n", "\t": r"\t", "\r": r"\r"}[ch]
    if cp < 0x20 or cp >= 0x7F:
        return f"\\u{{{cp:x}}}"
    return "\\" + ch if ch in (CLASS_SPECIAL if in_class else SYNTAX) else ch


def _ranges(cps) -> str:
    """A compact class body for a set of code points."""
    cps, out = sorted(cps), []
    for _, run in itertools.groupby(enumerate(cps), key=lambda t: t[1] - t[0]):
        run = [cp for _, cp in run]
        out.append(_char(run[0], True) if len(run) == 1 else
                   _char(run[0], True) + ("" if len(run) == 2 else "-") + _char(run[-1], True))
    return "".join(out)


class _Translator:
    def __init__(self, pattern: str, flags: int):
        self.p, self.i, self.flags = pattern, 0, int(flags)
        self.space = _ranges(python_whitespace())

    def fail(self, why: str):
        raise Untranslatable(f"{why} at offset {self.i} in {self.p!r}")

    def _escape_cp(self, in_class: bool) -> Optional[int]:
        """Consume an escape that denotes a single code point; None (cursor untouched) if it is not one."""
        p, i = self.p, self.i
        c = p[i + 1]
        if c in SIMPLE_ESCAPES or (c == "b" and in_class):
            self.i = i + 2
            return SIMPLE_ESCAPES.get(c, 0x08)
        for prefix, width in (("x", 2), ("u", 4), ("U", 8)):
            if c == prefix:
                self.i = i + 2 + width
                return int(p[i + 2:self.i], 16)
        if c == "N":
            end = p.index("}", i)
            self.i = end + 1
            return ord(unicodedata.lookup(p[i + 3:end]))
        if c == "0" or (in_class and c in "1234567"):
            digits = re.match(r"[0-7]{1,3}", p[i + 1:]).group(0)
            self.i = i + 1 + len(digits)
            return int(digits, 8)
        if c.isascii() and not c.isalnum():
            self.i = i + 2
            return ord(c)
        return None

    def _class_cp(self) -> int:
        if self.p[self.i] == "\\":
            cp = self._escape_cp(in_class=True)
            if cp is None:
                self.fail("unsupported escape in a set")
            return cp
        self.i += 1
        return ord(self.p[self.i - 1])

    def _class(self) -> str:
        start = self.i
        self.i += 1
        negate = self.p.startswith("^", self.i)
        self.i += negate
        items: List[str] = []
        cats = set()
        first = True
        while True:
            if self.i >= len(self.p):
                self.fail("unterminated set")
            if self.p[self.i] == "]" and not first:
                self.i += 1
                break
            first = False
            if self.p[self.i] == "\\" and self.p[self.i + 1] in "wWdDsS":
                cats.add(self.p[self.i + 1])
                self.i += 2
                continue
            lo = self._class_cp()
            if self.p.startswith("-", self.i) and not self.p.startswith("-]", self.i):
                self.i += 1
                items.append(_char(lo, True) + "-" + _char(self._class_cp(), True))
            else:
                items.append(_char(lo, True))
        source = self.p[start:self.i]
        if cats & set("WS"):
            if cats in ({"s", "S"}, {"w", "W"}) and not items:
                return r"[^\s\S]" if negate else r"[\s\S]"
            self.fail(r"negated class escape (\W, \S) inside a set")
        body = "".join(items) + "".join({"w": WORD, "d": r"\p{Nd}", "D": r"\P{Nd}", "s": self.space}[c] for c in sorted(cats))
        out = ("[^" if negate else "[") + body + "]"
        if self.flags & re.IGNORECASE:
            added, removed = _case_delta(source)
            if added:
                out = f"[{body}{_ranges(added)}]" if not negate else f"(?:{out}|[{_ranges(added)}])"
            if removed:
                out = f"(?:(?![{_ranges(removed)}]){out})"
        return out

    def _literal(self, cp: int) -> str:
        if self.flags & re.IGNORECASE:
            added, removed = _case_delta(re.escape(chr(cp)))
            if removed:
                self.fail("IGNORECASE removes characters from a literal")
            if added:
                return f"[{_ranges((cp, *added))}]"
        return _char(cp, False)

    def _group(self) -> str:
        p, i = self.p, self.i
        if not p.startswith("(?", i):
            self.i += 1
            return "("
        for same in ("(?:", "(?=", "(?!", "(?<=", "(?<!"):
            if p.startswith(same, i):
                self.i += len(same)
                return same
        if p.startswith("(?P<", i):
            end = p.index(">", i)
            name = p[i + 4:end]
            if not re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name):
                self.fail(f"group name {name!r} is not a JavaScript identifier")
            self.i = end + 1
            return f"(?<{name}>"
        if p.startswith("(?P=", i):
            if self.flags & re.IGNORECASE:
                self.fail("case-insensitive backreference")
            end = p.index(")", i)
            self.i = end + 1
            return f"\\k<{p[i + 4:end]}>"
        if p.startswith("(?#", i):
            self.i = p.index(")", i) + 1
            return ""
        self.fail("atomic group, conditional or inline flags")

    def translate(self) -> str:
        p = self.p
        lead = re.match(r"\(\?([a-zA-Z]+)\)", p)
        if lead:
            for f in lead.group(1):
                self.flags |= int(INLINE_FLAGS.get(f, 1 << 30))
            self.i = lead.end()
        if self.flags & ~SUPPORTED_FLAGS:
            self.fail("unsupported flag (only IGNORECASE, MULTILINE and DOTALL translate)")
        out: List[str] = []
        repeatable = False
        while self.i < len(p):
            ch = p[self.i]
            m = REPEAT.match(p, self.i) if ch == "{" else None
            if ch == "\\":
                nxt = p[self.i + 1]
                if nxt in "AZBGz":
                    self.fail(f"\\{nxt} has no faithful JavaScript translation")
                if nxt in "wWdDsSb":
                    out.append({"w": f"[{WORD}]", "W": f"[^{WORD}]", "d": r"\p{Nd}", "D": r"\P{Nd}",
                                "s": f"[{self.space}]", "S": f"[^{self.space}]", "b": WORD_BOUNDARY}[nxt])
                    self.i += 2
                    repeatable = nxt != "b"
                    continue
                if nxt in "123456789":
                    if self.flags & re.IGNORECASE:
                        self.fail("case-insensitive backreference")
                    ref = re.match(r"[0-9]{1,2}", p[self.i + 1:]).group(0)
                    out.append("\\" + ref)
                    self.i += 1 + len(ref)
                    repeatable = True
                    continue
                cp = self._escape_cp(in_class=False)
                if cp is None:
                    self.fail(f"unsupported escape \\{nxt}")
                out.append(self._literal(cp))
                repeatable = True
            elif ch == "[":
                out.append(self._class())
                repeatable = True
            elif ch == "(":
                out.append(self._group())
                repeatable = False
            elif ch in ")|.^$":
                out.append({")": ")", "|": "|", ".": r"[\s\S]" if self.flags & re.DOTALL else r"[^\n]",
                            "^": r"(?<![^\n])" if self.flags & re.MULTILINE else "^",
                            "$": r"(?=\n|(?![\s\S]))" if self.flags & re.MULTILINE else r"(?=\n?(?![\s\S]))"}[ch])
                self.i += 1
                repeatable = ch in ")."
            elif ch in "*+?" or (m and (m.group(1) or m.group(2))):
                if not repeatable:
                    self.fail("nothing to repeat")
                if m:
                    lo, comma, hi = m.groups()
                    out.append("{" + (lo or "0") + comma + hi + "}")
                    self.i = m.end()
                else:
                    out.append(ch)
                    self.i += 1
                if p.startswith("+", self.i):
                    self.fail("possessive quantifier")
                if p.startswith("?", self.i):
                    out.append("?")
                    self.i += 1
                repeatable = False
            else:
                out.append(self._literal(ord(ch)))
                self.i += 1
                repeatable = True
        return "".join(out)


def py_flags(flags: int) -> str:
    return "".join(f for f, bit in INLINE_FLAGS.items() if f != "u" and flags & bit)


def regex(rx, call: str, flags: int = 0) -> dict:
    """A JS regex spec for a compiled pattern (or pattern string). `call` is how Python applies it: "match" specs
    are anchored here, so exec/test reproduce re.match; findall/finditer/sub/split need a "g" flag added."""
    pattern, flags = (rx.pattern, int(rx.flags) & ~int(re.UNICODE)) if isinstance(rx, re.Pattern) else (rx, flags)
    re.compile(pattern, flags)
    source = _Translator(pattern, flags).translate()
    if call == "match":
        source = f"^(?:{source})"
    return {"pattern": source, "flags": "u", "call": call, "python": {"pattern": pattern, "flags": py_flags(flags)}}

