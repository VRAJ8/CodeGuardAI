r"""Exports the scan engine to the in-browser engine (frontend/src/lib/engine).

    python -m codeguard.browser_export          # rewrite rules.generated.json and parity.golden.json
    python -m codeguard.browser_export --check  # exit 1 if either file is stale (tests/test_browser_parity.py)

Python stays the single source of truth. rules.generated.json carries every rule, regex and constant the browser
engine needs, imported from the engine modules rather than retyped. parity.golden.json records what this engine
reports on a test corpus under browser semantics (no Bandit or Semgrep, the generic complexity heuristic for every
file, OSV off or mocked), and jest asserts the JavaScript engine reproduces it exactly.

Regexes become `new RegExp(pattern, "u")` sources with Python's semantics written out, because the dialects
disagree on Unicode: Python's \w is exactly [\p{L}\p{N}_], its \s includes U+001C-U+001F and U+0085 but not
U+FEFF, "." stops only at "\n", "$" also matches before a final newline, and IGNORECASE matches U+0130/U+0131 for
"i" while JS's i flag folds characters such as U+0345 into letters. IGNORECASE is therefore compiled into explicit
per-character sets computed from Python itself. Constructs without a faithful translation (\A, \Z, \B, atomic
groups, possessive quantifiers, conditionals, local or verbose flags, case-insensitive backreferences) raise.

Float results must not hinge on libm or summation details that differ between CPython builds and V8, so the golden
is rebuilt under Python 3.11 and 3.12 summation and with exp/log2 nudged a few ulps, and must come out identical.
"""
